// Guardar en archivo .env
const saveEnv = (updates) => {
  const envPath = path.join(__dirname, "..", ".env");

  let envContent = "";
  if (fs.existsSync(envPath)) {
    envContent = fs.readFileSync(envPath, "utf-8");
  }

  // Actualizar o agregar cada variable
  for (const [key, value] of Object.entries(updates)) {
    const regex = new RegExp(`^${key}=.*$`, "m");
    if (regex.test(envContent)) {
      envContent = envContent.replace(regex, `${key}=${value}`);
    } else {
      envContent += `\n${key}=${value}`;
    }
  }

  fs.writeFileSync(envPath, envContent, "utf-8");
  return envPath;
};

// Generar script para Vercel CLI
const generateVercelScript = (updates) => {
  const scriptPath = path.join(__dirname, "update-vercel-env.sh");

  let script = "#!/bin/bash\n\n# Script para actualizar variables en Vercel\n";
  script += "# Ejecutar: bash scripts/update-vercel-env.sh\n\n";

  for (const [key, value] of Object.entries(updates)) {
    script += `echo "Updating ${key}..."\n`;
    script += `vercel env add ${key}\n`;
    script += `# Pega: ${value}\n\n`;
  }

  fs.writeFileSync(scriptPath, script, "utf-8");
  return scriptPath;
};

